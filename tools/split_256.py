"""Generate the two runnable halves of the 256-token extraction from the template.

The (0, 100] corpus is 62,870 issues; at [256, 768] float16 that is 24.7 GB, over Kaggle's
20 GB kernel-output limit, so the extraction is split into two balanced kernels by assigning
projects round-robin from largest to smallest.

    python tools/split_256.py <path-to-all_issues_sp.csv>

Writes src/11a_extract_bert256_a.py and src/11b_extract_bert256_b.py from the template
src/11_extract_bert256.py and prints the split. Re-run after the template changes.
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "src" / "11_extract_bert256.py"


def balanced_split(csv_path):
    df = pd.read_csv(csv_path)
    df["storypoint"] = pd.to_numeric(df["storypoint"], errors="coerce")
    df = df.dropna(subset=["storypoint"])
    df = df[(df.storypoint > 0) & (df.storypoint <= 100)]
    sizes = df.groupby("project").size().sort_values(ascending=False)
    halves = {"a": [], "b": []}
    load = {"a": 0, "b": 0}
    for proj, n in sizes.items():
        k = "a" if load["a"] <= load["b"] else "b"
        halves[k].append(str(proj))
        load[k] += int(n)
    return halves, load, len(df)


def main():
    csv_path = sys.argv[1] if len(sys.argv) > 1 else \
        str(Path.home() / ".cache/kagglehub/datasets/ettasrinithreddy/tawos-extracted/versions/2/all_issues_sp.csv")
    halves, load, n_total = balanced_split(csv_path)
    template = TEMPLATE.read_text(encoding="utf-8")
    for half in ("a", "b"):
        src = template.replace("__HALF__", half).replace(
            "__PROJECTS_JSON__", json.dumps(halves[half], ensure_ascii=False, indent=4))
        out = ROOT / "src" / f"11{half}_extract_bert256_{half}.py"
        header = ("# GENERATED by tools/split_256.py from src/11_extract_bert256.py - edit the\n"
                  "# template and re-run the tool; do not edit this file directly.\n\n")
        out.write_text(header + src, encoding="utf-8")
        print(f"wrote {out.name}: {len(halves[half])} projects, {load[half]} issues "
              f"({load[half] * 256 * 768 * 2 / 1e9:.1f} GB)")
    print(f"total (0,100] issues: {n_total} | split file sizes sum to "
          f"{(load['a'] + load['b']) * 256 * 768 * 2 / 1e9:.1f} GB")
    (ROOT / "results" / "split_256_manifest.json").write_text(
        json.dumps({"a": halves["a"], "b": halves["b"], "issues": {"a": load["a"], "b": load["b"]}},
                   indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
